export function pickLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'es' || q === 'en') return q;
  return (navigator.language || 'es').toLowerCase().startsWith('es') ? 'es' : 'en';
}

export const nf = (lang, n, o = {}) =>
  new Intl.NumberFormat(lang === 'es' ? 'es-ES' : 'en-GB', { useGrouping: 'always', ...o }).format(n);

// Fill every [data-k] element with its string. Returns nothing.
export function applyText(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-k]').forEach((el) => {
    const v = S[lang][el.dataset.k];
    if (v != null) el.textContent = v;
  });
  document.querySelectorAll('[data-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
}
